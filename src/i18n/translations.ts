/**
 * Format currency in Bangladeshi Taka (৳)
 */
export const formatBDT = (amount: number, lang: Language = 'en'): string => {
  const formatted = new Intl.NumberFormat('en-IN', {
    maximumFractionDigits: 0
  }).format(amount);
  
  if (lang === 'bn') {
    return `৳ ${toLocaleNumber(formatted, 'bn')}`;
  }
  return `৳ ${formatted}`;
};
