/**
 * Utility to convert English numbers to Bengali digits when language is Bengali
 */
export const toLocaleNumber = (num: number | string, lang: Language): string => {
  if (lang !== 'bn') return String(num);
  const bengaliDigits = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];
  return String(num).replace(/[0-9]/g, (w) => bengaliDigits[+w]);
};

